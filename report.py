"""Builds the downloadable PDF report (reportlab)."""
import html, io
from datetime import datetime
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, Preformatted, SimpleDocTemplate, Spacer, Table, TableStyle

PURPLE, BLUE, INK, MUTED = colors.HexColor("#7c3aed"), colors.HexColor("#2563eb"), colors.HexColor("#1a1a3a"), colors.HexColor("#5d5d88")
SEV = {"high": "#ef4444", "medium": "#f59e0b", "low": "#0ea5e9"}
SWAP = {"—": "-", "–": "-", "’": "'", "‘": "'", "“": '"', "”": '"', "→": "->", "≤": "<=", "≥": ">=", "…": "...", "×": "x", "²": "^2", "³": "^3", "₂": "2", "√": "sqrt", "≈": "~", "≠": "!="}

H = ParagraphStyle("h", fontName="Helvetica-Bold", fontSize=13, textColor=PURPLE, spaceBefore=14, spaceAfter=6)
B = ParagraphStyle("b", fontName="Helvetica", fontSize=9.5, leading=14, textColor=INK)
CODE = ParagraphStyle("c", fontName="Courier", fontSize=7.8, leading=10.2, textColor=INK, backColor=colors.HexColor("#f3f1ff"), borderPadding=7, borderColor=colors.HexColor("#d9d4ff"), borderWidth=0.6)


def clean(t) -> str:
    t = str(t).replace("\t", "    ")
    for a, b in SWAP.items():
        t = t.replace(a, b)
    return t.encode("cp1252", "replace").decode("cp1252")


def P(t, style=B):
    return Paragraph(html.escape(clean(t)), style)


def wrap_code(code: str, width=100) -> str:
    out = []
    for line in clean(code).splitlines():
        while len(line) > width:
            out.append(line[:width] + "\\")
            line = "    " + line[width:]
        out.append(line)
    return "\n".join(out)


def _page(c, doc):
    w, h = A4
    c.saveState()
    c.setFillColor(PURPLE); c.rect(0, h - 24 * mm, w, 24 * mm, stroke=0, fill=1)
    c.setFillColor(BLUE); c.rect(w * 0.6, h - 24 * mm, w * 0.4, 24 * mm, stroke=0, fill=1)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 17); c.drawString(15 * mm, h - 13 * mm, "AlgoShastra")
    c.setFont("Helvetica", 9); c.drawString(15 * mm, h - 19 * mm, "C++ DSA Optimization Report")
    c.drawRightString(w - 15 * mm, h - 13 * mm, datetime.now().strftime("%d %b %Y, %H:%M"))
    c.setFillColor(MUTED); c.setFont("Helvetica", 8)
    c.drawCentredString(w / 2, 9 * mm, f"Page {doc.page}  |  Generated by AlgoShastra with Gemini")
    c.restoreState()


def _table(rows, widths, head=True):
    t = Table([[P(c) if not hasattr(c, "wrap") else c for c in r] for r in rows], colWidths=widths)
    st = [("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#d9d4ff")), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
          ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5)]
    if head:
        st += [("BACKGROUND", (0, 0), (-1, 0), PURPLE)]
    t.setStyle(TableStyle(st))
    return t


def build_pdf(result: dict, bench: dict | None = None) -> bytes:
    hd = ParagraphStyle("hd", parent=B, textColor=colors.white, fontName="Helvetica-Bold")
    o, n = result["original"], result["optimized"]
    s = [P(result.get("problem", "Analysis"), ParagraphStyle("t", parent=B, fontSize=11.5, leading=16, fontName="Helvetica-Bold"))]
    s += [P(f"Technique: {result.get('technique', '-')}", ParagraphStyle("m", parent=B, textColor=MUTED))]

    s += [Paragraph("Complexity", H), _table([
        [P("", hd), P("Original", hd), P("Optimized", hd)],
        [P("Time"), P(o["time"]), P(n["time"])],
        [P("Space"), P(o["space"]), P(n["space"])],
    ], [35 * mm, 72 * mm, 72 * mm])]
    if o.get("explanation") or n.get("explanation"):
        s += [Spacer(1, 6), P("Original: " + o.get("explanation", "")), P("Optimized: " + n.get("explanation", ""))]

    s += [Paragraph("Identified bugs and edge cases", H)]
    if result.get("bugs"):
        for b in result["bugs"]:
            sev = str(b.get("severity", "low")).lower()
            col = SEV.get(sev, SEV["low"])
            cell = [Paragraph(f'<font color="{col}"><b>[{sev.upper()}]</b></font> <b>{html.escape(clean(b.get("title", "")))}</b>', B), P(b.get("detail", ""), ParagraphStyle("d", parent=B, textColor=MUTED))]
            t = Table([[cell]], colWidths=[179 * mm])
            t.setStyle(TableStyle([("LINEBEFORE", (0, 0), (0, 0), 3, colors.HexColor(col)), ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#faf9ff")), ("LEFTPADDING", (0, 0), (-1, -1), 9), ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
            s += [t, Spacer(1, 4)]
    else:
        s += [P("No bugs or edge-case risks found.")]

    s += [Paragraph("Why the optimized version is faster", H), P(result["logic"])]
    s += [Paragraph("Original code", H), Preformatted(wrap_code(result.get("_original", "")), CODE)]
    s += [Paragraph("Optimized code", H), Preformatted(wrap_code(result["optimized_code"]), CODE)]

    if bench and not bench.get("error") and bench.get("rows"):
        verdict = {True: "Outputs identical on every test size.", False: "WARNING: outputs differ.", None: "Outputs could not be compared."}[bench["match"]]
        f = lambda v: "timeout" if v != v or v is None else f"{v:.2f}"
        rows = [[P("n", hd), P("Original (ms)", hd), P("Optimized (ms)", hd)]] + [[P(r["n"]), P(f(r["original_ms"])), P(f(r["optimized_ms"]))] for r in bench["rows"]]
        s += [Paragraph("Verification and benchmark", H), P(verdict), Spacer(1, 6), _table(rows, [35 * mm, 72 * mm, 72 * mm])]

    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=32 * mm, bottomMargin=18 * mm, title="AlgoShastra Report").build(s, onFirstPage=_page, onLaterPages=_page)
    return buf.getvalue()
